create or replace function public.is_attendance_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.guru where id = auth.uid() and role::text = 'admin');
$$;
revoke all on function public.is_attendance_admin() from public;
grant execute on function public.is_attendance_admin() to authenticated;

create or replace function public.attendance_status_options()
returns text[] language plpgsql stable security definer set search_path = '' as $$
begin
  if not public.is_attendance_admin() then
    raise exception 'Hanya admin yang dapat mengoreksi presensi.' using errcode = '42501';
  end if;
  return array(select unnest(enum_range(null::public.status_absensi))::text);
end;
$$;
revoke all on function public.attendance_status_options() from public;
grant execute on function public.attendance_status_options() to authenticated;

alter table public.surat
  add column if not exists reviewed_by uuid references public.guru(id) on delete set null,
  add column if not exists reviewed_at timestamptz;

create table if not exists public.absensi_audit (
  id bigint generated by default as identity primary key,
  absensi_id integer references public.absensi(id) on delete set null,
  surat_id integer references public.surat(id) on delete set null,
  actor_id uuid not null,
  actor_name text not null,
  source text not null check (source in ('manual', 'surat')),
  reason text not null check (length(btrim(reason)) > 0),
  before_data jsonb,
  after_data jsonb not null,
  created_at timestamptz not null default now()
);
create index if not exists absensi_audit_record_idx on public.absensi_audit(absensi_id, created_at desc);
alter table public.absensi_audit enable row level security;
revoke all on public.absensi_audit from anon, authenticated;
grant select on public.absensi_audit to authenticated;
drop policy if exists attendance_admin_read_audit on public.absensi_audit;
create policy attendance_admin_read_audit on public.absensi_audit for select to authenticated
  using (public.is_attendance_admin());

create or replace function public.correct_absensi(
  p_id integer, p_status text, p_waktu_masuk time, p_waktu_pulang time,
  p_keterangan text, p_reason text, p_expected jsonb
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_before public.absensi%rowtype;
  v_after public.absensi%rowtype;
  v_name text;
  v_student integer;
begin
  if not public.is_attendance_admin() then
    raise exception 'Hanya admin yang dapat mengoreksi presensi.' using errcode = '42501';
  end if;
  if nullif(btrim(p_reason), '') is null then
    raise exception 'Alasan perubahan wajib diisi.' using errcode = '22023';
  end if;
  if p_expected is null or not (p_expected ?& array['status','waktu_masuk','waktu_pulang','keterangan','updated_at']) then
    raise exception 'Snapshot presensi diperlukan. Muat ulang data.' using errcode = '22023';
  end if;
  select siswa_id into v_student from public.absensi where id = p_id;
  if not found then raise exception 'Presensi tidak ditemukan.'; end if;
  -- Same parent/row lock order as approval; serializes changes for this student.
  perform 1 from public.siswa where id = v_student for update;
  select * into strict v_before from public.absensi where id = p_id for update;
  if v_before.status::text is distinct from (p_expected->>'status')
     or v_before.waktu_masuk is distinct from (p_expected->>'waktu_masuk')::time
     or v_before.waktu_pulang is distinct from (p_expected->>'waktu_pulang')::time
     or v_before.keterangan is distinct from (p_expected->>'keterangan')
     or v_before.updated_at is distinct from (p_expected->>'updated_at')::timestamptz then
    raise exception 'Presensi telah berubah. Muat ulang sebelum mengedit.' using errcode = '40001';
  end if;
  if p_status in ('izin','sakit','alfa','alpa') and (p_waktu_masuk is not null or p_waktu_pulang is not null) then
    raise exception 'Status tidak hadir tidak boleh memiliki waktu masuk/pulang.' using errcode = '22023';
  end if;
  if p_status in ('hadir','terlambat','pulang') and p_waktu_masuk is null then
    raise exception 'Waktu masuk wajib diisi untuk status hadir.' using errcode = '22023';
  end if;
  if p_status = 'pulang' and p_waktu_pulang is null then
    raise exception 'Waktu pulang wajib diisi.' using errcode = '22023';
  end if;
  if p_waktu_pulang < p_waktu_masuk then
    raise exception 'Waktu pulang tidak boleh sebelum waktu masuk.' using errcode = '22023';
  end if;
  select nama into v_name from public.guru where id = auth.uid();
  update public.absensi set status = p_status::public.status_absensi,
    waktu_masuk = p_waktu_masuk, waktu_pulang = p_waktu_pulang,
    keterangan = nullif(btrim(p_keterangan), ''), updated_by = auth.uid(), updated_at = clock_timestamp()
    where id = p_id returning * into v_after;
  insert into public.absensi_audit(absensi_id,actor_id,actor_name,source,reason,before_data,after_data)
    values(p_id,auth.uid(),v_name,'manual',btrim(p_reason),to_jsonb(v_before),to_jsonb(v_after));
  return to_jsonb(v_after);
end;
$$;
revoke all on function public.correct_absensi(integer,text,time,time,text,text,jsonb) from public;
grant execute on function public.correct_absensi(integer,text,time,time,text,text,jsonb) to authenticated;

create or replace function public.review_surat(p_id integer, p_approve boolean, p_note text)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  v_letter public.surat%rowtype;
  v_before public.absensi%rowtype;
  v_after public.absensi%rowtype;
  v_end date;
  v_day date;
  v_name text;
  v_status text := case when p_approve then 'disetujui' else 'ditolak' end;
begin
  if not public.is_attendance_admin() then
    raise exception 'Hanya admin yang dapat memverifikasi surat.' using errcode = '42501';
  end if;
  if p_approve is null then raise exception 'Keputusan wajib diisi.'; end if;
  select * into v_letter from public.surat where id = p_id for update;
  if not found then raise exception 'Surat tidak ditemukan.'; end if;
  -- A retry of an already completed decision is idempotent.
  if v_letter.status = v_status then return to_jsonb(v_letter); end if;
  if coalesce(v_letter.status, 'menunggu') <> 'menunggu' then
    raise exception 'Surat sudah diproses. Muat ulang daftar surat.' using errcode = '40001';
  end if;
  if not p_approve and nullif(btrim(p_note), '') is null then
    raise exception 'Alasan penolakan wajib diisi.' using errcode = '22023';
  end if;
  if p_approve then
    if v_letter.siswa_id is null then raise exception 'Surat tidak memiliki siswa.'; end if;
    v_end := coalesce(v_letter.tanggal_selesai, v_letter.tanggal);
    if v_end < v_letter.tanggal then raise exception 'Rentang tanggal surat tidak valid.'; end if;
    perform 1 from public.siswa where id = v_letter.siswa_id for update;
    if exists(select 1 from public.surat where siswa_id = v_letter.siswa_id and id <> p_id
      and status = 'disetujui' and tanggal <= v_end
      and coalesce(tanggal_selesai, tanggal) >= v_letter.tanggal) then
      raise exception 'Sudah ada surat disetujui pada rentang tersebut.';
    end if;
    if exists(select 1 from public.absensi where siswa_id = v_letter.siswa_id
      and tanggal between v_letter.tanggal and v_end and status::text in ('hadir','terlambat','pulang')) then
      raise exception 'Ada presensi hadir pada rentang surat. Tinjau/koreksi presensi tersebut dahulu.';
    end if;
    select nama into v_name from public.guru where id = auth.uid();
    for v_day in select generate_series(v_letter.tanggal::timestamp, v_end::timestamp, interval '1 day')::date loop
      v_before := null;
      select * into v_before from public.absensi where siswa_id = v_letter.siswa_id and tanggal = v_day for update;
      if found then
        if v_before.status::text in ('hadir','terlambat','pulang') then
          raise exception 'Presensi hadir berubah selama peninjauan. Muat ulang dan tinjau dahulu.' using errcode = '40001';
        end if;
        update public.absensi set status = v_letter.jenis::text::public.status_absensi,
          waktu_masuk = null, waktu_pulang = null,
          keterangan = 'Surat #' || p_id || coalesce(': ' || nullif(btrim(p_note), ''), ''),
          updated_by = auth.uid(), updated_at = clock_timestamp()
          where id = v_before.id returning * into v_after;
      else
        insert into public.absensi(siswa_id,tanggal,status,keterangan,updated_by)
          values(v_letter.siswa_id,v_day,v_letter.jenis::text::public.status_absensi,
            'Surat #' || p_id || coalesce(': ' || nullif(btrim(p_note), ''), ''),auth.uid()) returning * into v_after;
      end if;
      insert into public.absensi_audit(absensi_id,surat_id,actor_id,actor_name,source,reason,before_data,after_data)
        values(v_after.id,p_id,auth.uid(),v_name,'surat',coalesce(nullif(btrim(p_note), ''),'Persetujuan surat'),
          case when v_before.id is null then null else to_jsonb(v_before) end,to_jsonb(v_after));
    end loop;
  end if;
  update public.surat set status = v_status, catatan_guru = nullif(btrim(p_note), ''),
    reviewed_by = auth.uid(), reviewed_at = clock_timestamp() where id = p_id returning * into v_letter;
  return to_jsonb(v_letter);
end;
$$;
revoke all on function public.review_surat(integer,boolean,text) from public;
grant execute on function public.review_surat(integer,boolean,text) to authenticated;

-- Approval may create past/future attendance rows. Keep the existing webhook
-- handler/arguments, but send attendance notifications only for today's date.
-- Preserve any installation-specific WHEN condition if one already exists.
do $$
declare v_definition text;
begin
  select pg_get_triggerdef(oid) into v_definition from pg_trigger
    where tgrelid = 'public.absensi'::regclass and tgname = 'trigger_notifikasi_absensi' and not tgisinternal;
  if v_definition is not null and position(' WHEN (' in v_definition) = 0 then
    if position(' FOR EACH ROW EXECUTE FUNCTION ' in v_definition) = 0 then
      raise exception 'Format trigger notifikasi tidak dikenali; tinjau migration sebelum menerapkan.';
    end if;
    execute 'drop trigger trigger_notifikasi_absensi on public.absensi';
    execute replace(v_definition, ' FOR EACH ROW EXECUTE FUNCTION ',
      ' FOR EACH ROW WHEN (new.tanggal = (now() AT TIME ZONE ''Asia/Jakarta'')::date) EXECUTE FUNCTION ');
  end if;
end;
$$;

